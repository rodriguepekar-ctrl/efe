"""EFE Drift Monitoring (M09).

Public surface :

* :class:`DriftClient`            — one-stop SDK (L1 → L5).
* :class:`DriftSettings`          — configuration bundle.
* :class:`FeatureCatalog`         — feature registry (L1).
* :class:`FeatureSpec`            — feature declaration.
* :class:`PiiLinter`              — invariant-I6 enforcement.
* :class:`IngestionPipeline`      — per-event feature extraction.
* :class:`NatsConsumer`           — pull-based consumer.
* :class:`HistogramBuilder`       — L2 building block.
* :func:`rollup_samples`          — L2 rollup function.
* :class:`BaselineManager`        — L3 lifecycle orchestrator.
* :class:`BaselineCandidate`      — accumulation buffer.
* :func:`seal_baseline`           — HMAC seal.
* :class:`PsiDetector`, :class:`KsDetector`, :class:`ChiSquaredDetector`,
  :class:`WassersteinDetector`, :class:`MmdDetector`,
  :class:`ClassifierDriftDetector` — L4 detectors.
* :class:`DriftEvaluator`         — L4 orchestrator.
* :class:`AlertRouter`, :class:`AlertRule`, :class:`AlertIncident`,
  :class:`SlackChannel`, :class:`PagerDutyChannel`,
  :class:`WebhookChannel`, :class:`NatsAlertChannel` — L5 alerting.

Heavy sub-modules are lazily importable — top-level
``import efe_drift`` stays cheap.
"""

