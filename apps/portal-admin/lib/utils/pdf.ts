/**
 * Right-to-explanation PDF generator (GDPR Art. 22).
 *
 * Generates a PDF document explaining a Mode-3 classification :
 *   - Tenant + timestamp + audit_id
 *   - Sentence hash (PII-safe)
 *   - Final label + confidence
 *   - Concept stack turn-by-turn (anchors top-K, LLM reasoning, cost)
 *   - HMAC chain verification status
 *
 * Server-side only — uses pdfkit (Node native).
 */
import PDFDocument from "pdfkit";

interface ConceptStackEntry {
  swarm_confidence: number;
  converged: boolean;
  top_anchors: { anchor_id: string; text: string; label: string; score: number }[];
  llm_reasoning: string;
  provider_used: string;
  template_id: string;
  tokens_used: number;
  cost_usd: number;
  duration_ms: number;
}

export interface AuditDetail {
  audit_id: number;
  ts: string;
  tenant_id: string;
  mode: string;
  sentence_hash: string;
  label: string | null;
  confidence: number | null;
  duration_ms: number;
  chain_intact?: boolean;
  concept_stack?: { entries: ConceptStackEntry[] } | null;
}

export async function generateExplanationPdf(audit: AuditDetail): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Title: `EFE — Right to explanation — audit ${audit.audit_id}`,
        Author: "EFE Platform",
        Subject: "GDPR Art. 22 right-to-explanation export",
        Keywords: "gdpr, ai-act, classification, audit",
        CreationDate: new Date(),
      },
    });

    const chunks: Buffer[] = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", (err) => reject(err));

    // Title.
    doc.fontSize(20).fillColor("#000").text("EFE — Right to explanation", { align: "center" });
    doc.moveDown(0.5);
    doc
      .fontSize(10)
      .fillColor("#666")
      .text("GDPR Art. 22 + AI Act Art. 14 disclosure", { align: "center" });
    doc.moveDown(2);

    // Metadata block.
    doc.fontSize(11).fillColor("#000");
    doc.text(`Audit ID    : #${audit.audit_id}`);
    doc.text(`Tenant      : ${audit.tenant_id}`);
    doc.text(`Timestamp   : ${audit.ts}`);
    doc.text(`Mode        : ${audit.mode}`);
    doc.text(`Sentence    : SHA-256 ${audit.sentence_hash}`);
    doc.text(`Final label : ${audit.label ?? "(none)"} (${(audit.confidence ?? 0).toFixed(3)})`);
    doc.text(`Duration    : ${audit.duration_ms}ms`);
    doc.text(`Chain HMAC  : ${audit.chain_intact ? "✓ intact" : "✗ broken"}`);
    doc.moveDown(2);

    if (audit.mode === "MODE_3" && audit.concept_stack?.entries.length) {
      doc.fontSize(14).text("Concept stack — multi-turn reasoning trace");
      doc.moveDown();
      const entries = audit.concept_stack.entries;
      for (let idx = 0; idx < entries.length; idx++) {
        const entry = entries[idx];
        if (!entry) continue;
        doc
          .fontSize(12)
          .fillColor("#000")
          .text(`Turn ${idx + 1}`, { underline: true });
        doc.fontSize(10).fillColor("#000");
        doc.text(
          `  Confidence : ${entry.swarm_confidence.toFixed(3)}${entry.converged ? "  (converged)" : ""}`,
        );
        doc.text(`  Provider   : ${entry.provider_used} / template ${entry.template_id}`);
        doc.text(
          `  Tokens     : ${entry.tokens_used}    Cost: $${entry.cost_usd.toFixed(5)}    Latency: ${entry.duration_ms}ms`,
        );
        doc.moveDown(0.4);
        doc.text("  Top anchors:");
        for (const a of entry.top_anchors.slice(0, 5)) {
          doc.text(`    • [${a.label}] ${a.text} (${a.score.toFixed(3)})`);
        }
        doc.moveDown(0.4);
        doc.text("  LLM reasoning:");
        doc.fontSize(9).fillColor("#444");
        doc.text(entry.llm_reasoning, { indent: 20, lineGap: 1 });
        doc.moveDown(1);
      }
    } else {
      doc
        .fontSize(11)
        .fillColor("#666")
        .text("No multi-turn reasoning trace recorded for this audit row.");
    }

    // Footer.
    doc.fontSize(8).fillColor("#999");
    doc.text(
      `Generated by EFE Portal Admin on ${new Date().toISOString()}. This document constitutes the GDPR Art. 22 right-to-explanation disclosure.`,
      50,
      doc.page.height - 60,
      { width: doc.page.width - 100, align: "center" },
    );

    doc.end();
  });
}
