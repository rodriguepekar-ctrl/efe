//! PR #24 § 12 + AD24-AD28 — quarterly compliance evidence.
//!
//! Independent from PR #22 SLO quarterly evidence but **the bench
//! harness's verifier accepts BOTH PR #22 + PR #24 PDFs** via the
//! cross-chain identity regex below (AC22).  PR #22's verifier in
//! `crates/efe-slos/rollup/src/evidence/mod.rs` carries its own
//! narrower regex that ONLY accepts PR #22 PDFs — asymmetry is
//! intentional : the bench harness is the canonical cross-chain
//! verifier ; the SLO verifier stays scoped to its own chain.
//!
//! **D-T** : `SHARED_COSIGN_IDENTITY_REGEXP` historically named for
//! the lock-step intent.  Retained for ABI compat ; new code should
//! reference the more accurate alias [`CROSS_CHAIN_COSIGN_IDENTITY_REGEXP`].

pub mod json;
pub mod pdf;
pub mod sign;

/// AD25 + AC22 — frozen cross-chain identity regex.
///
/// Matches BOTH SLO + bench workflows.  Update **only** in lock-step
/// with PR #22's narrower regex AND a STABILITY_CONTRACT bump.
pub const SHARED_COSIGN_IDENTITY_REGEXP: &str =
    r"^https://github\.com/efe-ai/efe/\.github/workflows/(slo-quarterly|bench-publish-quarterly)\.yml@refs/.+$";

/// Alias for [`SHARED_COSIGN_IDENTITY_REGEXP`] with the honest name —
/// "shared" was misleading because PR #22 carries a narrower regex by
/// design.  This is the BENCH harness's cross-chain verifier regex.
pub const CROSS_CHAIN_COSIGN_IDENTITY_REGEXP: &str = SHARED_COSIGN_IDENTITY_REGEXP;

/// AD25 — frozen OIDC issuer (same as PR #22 § 22.8).
pub const COSIGN_OIDC_ISSUER: &str = "https://token.actions.githubusercontent.com";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shared_identity_regex_locked_v1_6() {
        // STABILITY_CONTRACT v1.6 § 24.8.
        assert!(SHARED_COSIGN_IDENTITY_REGEXP.contains("efe-ai/efe"));
        assert!(SHARED_COSIGN_IDENTITY_REGEXP.contains("slo-quarterly"));
        assert!(SHARED_COSIGN_IDENTITY_REGEXP.contains("bench-publish-quarterly"));
    }

    #[test]
    fn oidc_issuer_matches_pr22() {
        assert_eq!(COSIGN_OIDC_ISSUER, "https://token.actions.githubusercontent.com");
    }

    /// **D-T** — sanity test : the cross-chain regex MUST accept every
    /// OIDC subject PR #22's narrower verifier accepts.  Failure here
    /// means cross-chain verification of PR #22 PDFs is broken.
    ///
    /// Honest note on regex looseness : the `refs/.+$` tail is greedy
    /// and accepts any non-empty suffix.  This is safe in practice
    /// because the OIDC subject is generated by GitHub Actions (not
    /// attacker-controlled) and Git ref names already exclude shell
    /// metacharacters.  Tightening this would require a STABILITY
    /// bump — out of scope for v1.6 — see PR #25 candidate.
    #[test]
    fn cross_chain_regex_accepts_pr22_oidc_subjects() {
        let re = regex::Regex::new(SHARED_COSIGN_IDENTITY_REGEXP).expect("regex must compile");
        // The exact OIDC subject GitHub produces for a slo-quarterly
        // workflow run on the main branch.
        assert!(re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/slo-quarterly.yml@refs/heads/main"
        ));
        // Tag refs.
        assert!(re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/slo-quarterly.yml@refs/tags/v0.6.0"
        ));
        // Bench equivalent.
        assert!(re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/bench-publish-quarterly.yml@refs/heads/main"
        ));
        // Negative : different workflow must NOT match (group alternation).
        assert!(!re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/random-workflow.yml@refs/heads/main"
        ));
        // Negative : different repo must NOT match.
        assert!(!re.is_match(
            "https://github.com/attacker/efe/.github/workflows/bench-publish-quarterly.yml@refs/heads/main"
        ));
        // Negative : missing @refs/ suffix must NOT match.
        assert!(!re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/bench-publish-quarterly.yml"
        ));
        // Negative : empty ref name must NOT match (`.+` requires ≥ 1 char).
        assert!(!re.is_match(
            "https://github.com/efe-ai/efe/.github/workflows/bench-publish-quarterly.yml@refs/"
        ));
    }

    #[test]
    fn cross_chain_alias_equals_shared() {
        // D-T : the more-honestly-named alias must be byte-identical.
        assert_eq!(SHARED_COSIGN_IDENTITY_REGEXP, CROSS_CHAIN_COSIGN_IDENTITY_REGEXP);
    }
}
