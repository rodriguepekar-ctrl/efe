/// Helpers to convert between proto types and idiomatic Rust types.
///
/// These intentionally do NOT depend on the `efe-meta-swarm` crate.
/// Conversions go through plain `Vec<f32>` / `f64` etc., keeping
/// `efe-meta-swarm-proto` dependency-light and safe to import from
/// any consumer crate.
pub mod conv {
    use super::meta_swarm::TensorF32;

    /// Build a `TensorF32` from a `&[f32]`.  Cheap : one `Vec`
    /// allocation + copy.
    #[must_use]
    pub fn tensor_from_slice(data: &[f32]) -> TensorF32 {
        TensorF32 {
            dim: u32::try_from(data.len()).expect("tensor dim must fit in u32"),
            data: data.to_vec(),
        }
    }

    /// Validate a `TensorF32` : `dim == data.len()`.  Returns the
    /// inner slice on success.  Used by the server-side parsing path
    /// (PR #8 + #9).
    ///
    /// # Errors
    /// Returns a static `&str` error when `dim != data.len()`.
    pub fn tensor_validate(t: &TensorF32) -> Result<&[f32], &'static str> {
        if t.dim as usize != t.data.len() {
            return Err("TensorF32 : dim != data.len()");
        }
        Ok(&t.data)
    }
}

// ---------------------------------------------------------------------------
//  Compile-time smoke : verifies that tonic-build emitted what we
//  expect.  If this stops compiling, a downstream crate would fail to
//  import the symbols — we fail loudly here instead.
// ---------------------------------------------------------------------------
#[allow(dead_code)]
fn _compile_time_smoke() {
    // Plain message types — always available.
    let _: Option<crate::meta_swarm::IterateRequest> = None;
    let _: Option<crate::meta_swarm::IterateResponse> = None;
    let _: Option<crate::meta_swarm::TensorF32> = None;
    let _: Option<crate::meta_swarm::HealthResponse> = None;

    // Enums — always available.
    let _: Option<crate::meta_swarm::MetaSwarmErrorCode> = None;
    let _: Option<crate::meta_swarm::StopReason> = None;

    // Client stubs — gated off the `server-only` feature.
    #[cfg(not(feature = "server-only"))]
    {
        let _: Option<crate::controller::MetaSwarmServiceClient<tonic::transport::Channel>> = None;
        let _: Option<crate::participant::MetaParticipantServiceClient<tonic::transport::Channel>> =
            None;
    }

    // Server traits — gated off the `client-only` feature.
    #[cfg(not(feature = "client-only"))]
    {
        // `MetaSwarmService` / `MetaParticipantService` are async
        // traits ; we only check that the names resolve.
        fn _check_server_trait_exists<T: crate::controller::MetaSwarmService>() {}
        fn _check_participant_trait_exists<T: crate::participant::MetaParticipantService>() {}
    }
}
