//! `efe-server` — gRPC surface of EFE (M10).
//!
//! See `M10_ARCHITECTURE.md` at the workspace root for the full design
//! rationale, versioning policy, and threat model.
//!
//! # Public surface
//!
//! The binary (`src/main.rs`) and the library (`src/lib.rs`) expose the
//! same building blocks so that integration tests can instantiate a
//! server in-process without launching a real listener when desired.
//!
//! ```ignore
//! use efe_server::{Server, ServerConfig};
//! # async fn example() -> anyhow::Result<()> {
//! let cfg = ServerConfig::default();
//! let server = Server::builder().config(cfg).build().await?;
//! // server.serve(addr, shutdown).await?;
//! # Ok(()) }
//! ```

