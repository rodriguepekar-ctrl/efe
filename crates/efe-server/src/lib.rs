/// Generated protobuf / tonic stubs for the `efe.v1` package.
///
/// The module hierarchy mirrors the `.proto` package hierarchy so that
/// cross-package references generated by `tonic-build` (e.g.
/// `super::AlignmentCone` inside `efe.v1.admin`) resolve correctly.
pub mod proto {

    /// `efe.v1` — shared types and the main `SwarmService`.
    /// Contains `AlignmentCone`, `Anchor`, etc. referenced by `admin`.
    pub mod v1 {
        #![allow(clippy::all, clippy::pedantic, missing_docs, unreachable_pub)]
        tonic::include_proto!("efe.v1");

        /// `efe.v1.admin` — the admin service (M9 governance).
        ///
        /// Nested here so that `super::AlignmentCone` resolves to
        /// `crate::proto::v1::AlignmentCone` as the code generator
        /// expects.
        pub mod admin {
            #![allow(clippy::all, clippy::pedantic, missing_docs, unreachable_pub)]
            tonic::include_proto!("efe.v1.admin");
        }

        /// Sprint **D12-bis** — `efe.v1.catalog` : catalog admin
        /// service (6 RPCs : Register/Evolve/Get/List/ListVersions/
        /// Delete).
        ///
        /// The proto file lives in `protos/efe/v1/catalog.proto` ;
        /// `build.rs` includes it in the tonic-build invocation
        /// since D12-bis. Before D12-bis the Rust stubs were
        /// missing — only Python had them.
        pub mod catalog {
            #![allow(clippy::all, clippy::pedantic, missing_docs, unreachable_pub)]
            tonic::include_proto!("efe.v1.catalog");
        }

        /// Sprint **D34** (M4 § 13) — `efe.v1.mode2` : dynamic-anchor
        /// service. Generated stubs : `Mode2Service` server + client.
        ///
        /// Three built-in routers are wired in `services::mode2` :
        ///   * `mock` — deterministic SHA-256-seeded anchors.
        ///   * `openai` — gpt-4o-mini routing (D35 follow-up).
        ///   * `anthropic` — claude-haiku routing (D36 follow-up).
        pub mod mode2 {
            #![allow(clippy::all, clippy::pedantic, missing_docs, unreachable_pub)]
            tonic::include_proto!("efe.v1.mode2");
        }

        /// Sprint **D37** (M4 § 14) — `efe.v1.mode3` : multi-turn
        /// parallel service. Generated stubs : `Mode3Service` server
        /// + client.
        ///
        /// Three built-in aggregators are wired in `services::mode3` :
        ///   * `mean`     — element-wise mean of centroids.
        ///   * `weighted` — weighted by per-sub-swarm confidence.
        ///   * `median`   — coordinate-wise median.
        pub mod mode3 {
            #![allow(clippy::all, clippy::pedantic, missing_docs, unreachable_pub)]
            tonic::include_proto!("efe.v1.mode3");
        }
    }

    /// Alias for the admin package to keep short paths in handlers.
    pub use v1::admin as v1_admin;

    /// Alias for the catalog package (D12-bis) — short paths in
    /// `services/catalog.rs`.
    pub use v1::catalog as v1_catalog;

    /// Alias for the Mode-2 package (**D34**) — short paths in
    /// `services/mode2.rs`.
    pub use v1::mode2 as v1_mode2;

    /// Alias for the Mode-3 package (**D37**) — short paths in
    /// `services/mode3.rs`.
    pub use v1::mode3 as v1_mode3;

    /// File descriptor set bytes for tonic reflection.
    pub const FILE_DESCRIPTOR_SET: &[u8] = tonic::include_file_descriptor_set!("efe_v1_descriptor");
}

