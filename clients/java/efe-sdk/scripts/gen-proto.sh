#!/usr/bin/env bash
# Sprint D26 (Φ-B) — regenerate Java proto stubs via protobuf-maven-plugin.
#
# Replaces the hand-coded placeholders in `efe-sdk-core/src/main/java/efe/v1/*.java`
# with the real `protoc + protoc-gen-grpc-java` output (compiled into
# `target/generated-sources/protobuf/{java,grpc-java}/`).
#
# Pre-requisites :
#
#   - mvnw (Maven Wrapper) committed in the repo, OR maven 3.9+ on PATH.
#   - JDK 17+ on PATH.
#   - protoc + protoc-gen-grpc-java are downloaded automatically by the
#     plugin from Maven Central — no host install needed.
#
# Pin tested by `test_d26_java_sdk_protos_in_sync` (Python).

set -euo pipefail
IFS=$'\n\t'

cd "$(dirname "${BASH_SOURCE[0]}")/.."

REPO_ROOT="$(cd ../../.. && pwd)"
PROTOS_DIR="$REPO_ROOT/protos"
CORE_PROTO_DIR="efe-sdk-core/src/main/proto"
HASH_FILE="$CORE_PROTO_DIR/PROTOS_HASH.txt"

log() { echo "[$(date -u +%FT%TZ)] $*" >&2; }

# 1. Sync protos/ → src/main/proto/ (copy — protobuf-maven-plugin needs a real path).
log "Syncing protos/efe/v1/*.proto → $CORE_PROTO_DIR/efe/v1/ ..."
mkdir -p "$CORE_PROTO_DIR/efe/v1"
cp "$PROTOS_DIR/efe/v1/"*.proto "$CORE_PROTO_DIR/efe/v1/" 2>/dev/null || \
    log "WARN: no protos in $PROTOS_DIR/efe/v1/ (real protos arrive via Lettre E)"

# 2. Run mvn generate-sources.
log "Running ./mvnw -pl efe-sdk-core generate-sources ..."
if [[ -x ./mvnw ]]; then
    ./mvnw -pl efe-sdk-core generate-sources
elif command -v mvn >/dev/null 2>&1; then
    mvn -pl efe-sdk-core generate-sources
else
    log "FATAL: neither mvnw nor mvn in PATH"
    exit 2
fi
log "✅ protoc + grpc-java generation complete (output in target/generated-sources/)"

# 3. Update PROTOS_HASH.txt.
log "Updating PROTOS_HASH.txt ..."
{
    echo "# Generated by scripts/gen-proto.sh — DO NOT EDIT BY HAND."
    echo "# One line per .proto file : <sha256>  <relative-path>."
    echo "# Pin tested by 'test_d26_java_sdk_protos_in_sync' (Python)."
    echo
    for proto in types.proto efe.proto catalog.proto admin.proto; do
        if [[ -f "$CORE_PROTO_DIR/efe/v1/$proto" ]]; then
            h=$(shasum -a 256 "$CORE_PROTO_DIR/efe/v1/$proto" 2>/dev/null \
                || sha256sum "$CORE_PROTO_DIR/efe/v1/$proto" 2>/dev/null \
                || echo "<no-sha-tool> $proto")
            echo "$h" | awk '{print $1, "'"$proto"'"}'
        fi
    done
} > "$HASH_FILE"

log "✅ done. Hash file at $HASH_FILE"
log
log "Next steps :"
log "  $ ./mvnw -pl efe-sdk-core compile"
log "  $ ./mvnw test"
