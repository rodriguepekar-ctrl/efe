#!/usr/bin/env bash
# Sprint D24 (Φ-B) — regenerate TS proto stubs via buf.
#
# Replaces the hand-coded placeholders in `src/_generated/efe/v1/*.ts`
# with the real `protoc-gen-es` + `protoc-gen-connect-es` output.
#
# Pre-requisites :
#
#   brew install bufbuild/buf/buf       # buf CLI
#   pnpm install                         # workspace deps incl. plugins
#
# After running, the hand-coded placeholders are REPLACED. The pin
# test `test_d24_typescript_sdk_protos_in_sync` (Python) verifies that
# the SHA-256 of `protos/efe/v1/*.proto` matches the values committed
# in `src/_generated/PROTOS_HASH.txt`. Drift → CI fail.
#
# Cf. docs/EFE_TYPESCRIPT_SDK_EXTENSION_ARCHITECTURE.md §11.

set -euo pipefail
IFS=$'\n\t'

cd "$(dirname "${BASH_SOURCE[0]}")/.."

REPO_ROOT="$(cd ../../../.. && pwd)"
PROTOS_DIR="$REPO_ROOT/protos"
OUT_DIR="src/_generated"
HASH_FILE="$OUT_DIR/PROTOS_HASH.txt"

log() { echo "[$(date -u +%FT%TZ)] $*" >&2; }

# 1. Pre-flight — toolchain.
for bin in buf node pnpm; do
    if ! command -v "$bin" >/dev/null 2>&1; then
        log "FATAL: $bin not in PATH"
        log "hint: install via :"
        log "  brew install bufbuild/buf/buf  # buf CLI"
        log "  brew install node              # Node ≥ 18"
        log "  npm i -g pnpm@9                # pnpm"
        exit 2
    fi
done
log "✅ buf + node + pnpm present"

# 2. Ensure plugins installed.
pnpm install --frozen-lockfile >/dev/null
log "✅ pnpm install complete"

# 3. Clean previous codegen (preserve PROTOS_HASH.txt).
log "Cleaning $OUT_DIR/efe/v1/*.ts ..."
find "$OUT_DIR/efe/v1" -maxdepth 1 -name '*.ts' -delete 2>/dev/null || true

# 4. Generate.
log "Running buf generate ..."
buf generate

log "✅ buf generate output written to $OUT_DIR/efe/v1/"

# 5. Update PROTOS_HASH.txt (anti-drift).
log "Updating PROTOS_HASH.txt..."
{
    echo "# Generated by scripts/gen-proto.sh — DO NOT EDIT BY HAND."
    echo "# One line per .proto file : <sha256>  <relative-path>."
    echo "# Pin tested by 'test_d24_typescript_sdk_protos_in_sync' (Python)."
    echo
    for proto in types.proto efe.proto catalog.proto admin.proto; do
        if [[ -f "$PROTOS_DIR/efe/v1/$proto" ]]; then
            h=$(shasum -a 256 "$PROTOS_DIR/efe/v1/$proto" 2>/dev/null \
                || sha256sum "$PROTOS_DIR/efe/v1/$proto" 2>/dev/null \
                || echo "<no-sha-tool> $proto")
            echo "$h" | awk '{print $1, "'"$proto"'"}'
        fi
    done
} > "$HASH_FILE"

log "✅ done. Hash file at $HASH_FILE"
log
log "Next steps :"
log "  $ pnpm typecheck"
log "  $ pnpm test"
