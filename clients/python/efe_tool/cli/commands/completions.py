"""Implementation of ``efe-admin completions {bash|zsh|fish}``.

Writes a completion script to stdout. The scripts are hand-written
rather than auto-generated by a third-party library (shtab, etc.) to
keep the runtime dependency footprint minimal. They hard-code the
current set of subcommands and the most-used flags.

When the CLI surface evolves, update :data:`_SUBCOMMANDS` and
:data:`_SHARED_FLAGS` — the templates interpolate them automatically.
"""

from __future__ import annotations

from typing import Final

from ..config import ResolvedConfig
from ..errors import UsageError
from ..logging import Logger


_SUBCOMMANDS: Final[tuple[str, ...]] = (
    "classify",
    "compile-catalog",
    "validate",
    "healthcheck",
    "eval",
    "version",
    "completions",
    "repl",                   # Letter B
    "scenario",               # Letter C
)


#: Scenario sub-sub-commands — completed after the user types ``:scenario``.
_SCENARIO_ACTIONS: Final[tuple[str, ...]] = (
    "list", "show", "run", "bench", "scaffold",
)


_SHARED_FLAGS: Final[tuple[str, ...]] = (
    "--help", "-h", "--version",
    "--log-level", "--log-format", "--quiet", "--no-color", "--request-id",
    "--endpoint", "--tls", "--tls-ca", "--jwt", "--tenant",
    "--catalog", "--embedder",
    "--budget-ms", "--timeout-s", "--max-rounds", "--strict",
    "--format", "--pretty", "--with-diagnostics",
    "--text", "--text-file", "--stdin",
    "--out", "--force",
    "--golden",
    "--strict-thresholds",
    # Letter B — REPL flags.
    "--history", "--no-history", "--prompt",
    # Letter C — scenario flags.
    "--user", "--transcript-path", "--cost-ceiling-usd", "--redact-user",
)


def run(cfg: ResolvedConfig, log: Logger) -> int:
    shell = cfg.shell
    if not shell:
        raise UsageError("completions: missing SHELL argument")
    if shell == "bash":
        script = _bash_script()
    elif shell == "zsh":
        script = _zsh_script()
    elif shell == "fish":
        script = _fish_script()
    else:  # pragma: no cover — guarded by argparse choices
        raise UsageError(f"completions: unsupported shell {shell!r}")

    print(script)
    log.debug("completions_emitted", shell=shell, bytes=len(script))
    return 0


# ---------------------------------------------------------------------------
#  Scripts
# ---------------------------------------------------------------------------


def _bash_script() -> str:
    cmds = " ".join(_SUBCOMMANDS)
    scen_actions = " ".join(_SCENARIO_ACTIONS)
    flags = " ".join(_SHARED_FLAGS)
    return f"""\
# efe-admin bash completion
_efe_admin_completions() {{
    local cur prev cmd
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    cmd="${{COMP_WORDS[1]}}"
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=($(compgen -W "{cmds}" -- "$cur"))
        return 0
    fi
    # Scenario sub-sub-command after `efe-admin scenario ...`.
    if [ "$cmd" = "scenario" ] && [ "$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=($(compgen -W "{scen_actions}" -- "$cur"))
        return 0
    fi
    case "$prev" in
        --catalog|--text-file|--tls-ca|--out|--golden|--history|--transcript-path)
            COMPREPLY=($(compgen -f -- "$cur")); return 0 ;;
        --log-level) COMPREPLY=($(compgen -W "debug info warn error" -- "$cur")); return 0 ;;
        --log-format) COMPREPLY=($(compgen -W "text json" -- "$cur")); return 0 ;;
        --format) COMPREPLY=($(compgen -W "json text table human" -- "$cur")); return 0 ;;
    esac
    COMPREPLY=($(compgen -W "{flags}" -- "$cur"))
}}
complete -F _efe_admin_completions efe-admin efe
"""


def _zsh_script() -> str:
    cmds = " ".join(_SUBCOMMANDS)
    scen_actions = " ".join(_SCENARIO_ACTIONS)
    flags = " ".join(_SHARED_FLAGS)
    return f"""\
#compdef efe-admin efe
# efe-admin zsh completion
_efe_admin() {{
  local -a subcommands scenario_actions
  subcommands=({cmds})
  scenario_actions=({scen_actions})
  if (( CURRENT == 2 )); then
    _describe -t commands 'efe-admin subcommand' subcommands
    return
  fi
  if [[ $words[2] == scenario && $CURRENT == 3 ]]; then
    _describe -t actions 'scenario action' scenario_actions
    return
  fi
  _arguments \\
    '--log-level[log level]:level:(debug info warn error)' \\
    '--log-format[log format]:format:(text json)' \\
    '--format[stdout format]:format:(json text table human)' \\
    '--catalog[catalog YAML path]:file:_files' \\
    '--text-file[UTF-8 file]:file:_files' \\
    '--tls-ca[CA bundle]:file:_files' \\
    '--out[output path]:file:_files' \\
    '--golden[golden set path]:file:_files' \\
    '*:flag:({flags})'
}}
_efe_admin "$@"
"""


def _fish_script() -> str:
    cmds = " ".join(_SUBCOMMANDS)
    lines = [
        "# efe-admin fish completion",
        "set -l __efe_admin_subcommands " + cmds,
        'complete -c efe-admin -n "__fish_use_subcommand" '
        '-a "$__efe_admin_subcommands"',
        'complete -c efe -n "__fish_use_subcommand" '
        '-a "$__efe_admin_subcommands"',
    ]
    # Emit one line per long flag so users get completion on any turn.
    for flag in _SHARED_FLAGS:
        if flag.startswith("--"):
            name = flag[2:]
            lines.append(f'complete -c efe-admin -l {name}')
            lines.append(f'complete -c efe -l {name}')
    return "\n".join(lines) + "\n"


__all__ = ["run"]
