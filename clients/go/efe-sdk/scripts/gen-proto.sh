#!/usr/bin/env bash
# Sprint D23 (Φ-B) — regenerate gRPC Go stubs from `protos/efe/v1/`.
#
# Cf. `docs/EFE_GO_SDK_EXTENSION_ARCHITECTURE.md` §11.
#
# Run :
#
#   ./scripts/gen-proto.sh
#
# Pre-requisites :
#
#   brew install protobuf       # protoc
#   go install google.golang.org/protobuf/cmd/protoc-gen-go@latest
#   go install google.golang.org/grpc/cmd/protoc-gen-go-grpc@latest
#
# After running, the hand-coded `internal/proto/efe/v1/types.go`
# is REPLACED by the protoc-gen-go output. The pin test
# `test_d23_go_sdk_protos_in_sync` (Python) verifies that the SHA-256
# of `protos/efe/v1/*.proto` matches the values committed in
# `internal/proto/efe/v1/PROTOS_HASH.txt`. Drift → CI fail.

set -euo pipefail
IFS=$'\n\t'

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
PROTOS_DIR="$REPO_ROOT/protos"
OUT_DIR="$REPO_ROOT/clients/go/efe-sdk/internal/proto"
HASH_FILE="$OUT_DIR/efe/v1/PROTOS_HASH.txt"

log() { echo "[$(date -u +%FT%TZ)] $*" >&2; }

# 1. Pre-flight : check toolchain.
for bin in protoc protoc-gen-go protoc-gen-go-grpc; do
    if ! command -v "$bin" >/dev/null 2>&1; then
        log "FATAL: $bin not in PATH"
        log "hint: install via :"
        log "  brew install protobuf"
        log "  go install google.golang.org/protobuf/cmd/protoc-gen-go@latest"
        log "  go install google.golang.org/grpc/cmd/protoc-gen-go-grpc@latest"
        exit 2
    fi
done
log "✅ protoc + plugins present"

# 2. Clean (idempotent — preserves PROTOS_HASH.txt).
log "Cleaning $OUT_DIR/efe/v1/*.pb.go ..."
find "$OUT_DIR/efe/v1" -maxdepth 1 -name '*.pb.go' -delete 2>/dev/null || true
# Also remove the hand-coded placeholder types.go ONLY if real
# protoc output is about to overwrite it.
if [[ -f "$OUT_DIR/efe/v1/types.go" ]]; then
    if grep -q "placeholder stubs" "$OUT_DIR/efe/v1/types.go" 2>/dev/null; then
        log "Removing hand-coded placeholder types.go"
        rm -f "$OUT_DIR/efe/v1/types.go"
    fi
fi

# 3. Generate.
log "Running protoc..."
mkdir -p "$OUT_DIR"
protoc \
    -I "$PROTOS_DIR" \
    --go_out="$OUT_DIR" \
    --go_opt=module=github.com/efe-ai/efe-sdk-go/internal/proto \
    --go-grpc_out="$OUT_DIR" \
    --go-grpc_opt=module=github.com/efe-ai/efe-sdk-go/internal/proto \
    "$PROTOS_DIR/efe/v1/types.proto" \
    "$PROTOS_DIR/efe/v1/efe.proto" \
    "$PROTOS_DIR/efe/v1/catalog.proto" \
    "$PROTOS_DIR/efe/v1/admin.proto"
log "✅ protoc-gen-go output written to $OUT_DIR/efe/v1/"

# 4. Update PROTOS_HASH.txt (anti-drift).
log "Updating PROTOS_HASH.txt..."
{
    echo "# Generated by scripts/gen-proto.sh — DO NOT EDIT BY HAND."
    echo "# One line per .proto file : `<sha256>  <relative-path>`."
    echo "# Pin tested by `test_d23_go_sdk_protos_in_sync` (Python)."
    echo
    for proto in types.proto efe.proto catalog.proto admin.proto; do
        if [[ -f "$PROTOS_DIR/efe/v1/$proto" ]]; then
            h=$(shasum -a 256 "$PROTOS_DIR/efe/v1/$proto" 2>/dev/null \
                || sha256sum "$PROTOS_DIR/efe/v1/$proto" 2>/dev/null \
                || echo "<no-sha-tool> $proto")
            echo "$h" | awk '{print $1, "'"$proto"'"}'
        fi
    done
} > "$HASH_FILE"

log "✅ done. Hash file at $HASH_FILE"
log
log "Next steps :"
log "  $ go build ./..."
log "  $ go test -race ./..."
