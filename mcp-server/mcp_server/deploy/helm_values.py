"""Helm values.yaml generator (M18 D49).

TM-M18-E-02 mitigation : we only emit sections from a strict whitelist
(`ALLOWED_HELM_SECTIONS`). Anything outside is silently dropped, even
if it appears in the input dataclass via subclassing.

`yaml.safe_dump` is the only serialiser used — no template engine, no
arbitrary expression evaluation. The output is plain text the operator
copy-pastes into their CD pipeline / runs `helm upgrade -f` against.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass
from typing import Any

import yaml


# Audit fix M18-FINAL-A6 (LOW) : `EFE_HELM_CHART_VERSION` must look
# like a semver (or short string) to be embedded in the YAML header.
# Anything containing newlines / control chars / colons could inject
# new YAML fields when the operator copy-pastes ; we silently drop
# such values (defense-in-depth ; the operator typically owns this
# env-var and won't attack themselves, but accidents happen).
_CHART_VERSION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._\-+]{0,30}$")


def _sanitise_chart_version(raw: str | None) -> str | None:
    if raw is None:
        return None
    raw = raw.strip()
    if not raw:
        return None
    return raw if _CHART_VERSION_RE.match(raw) else None


# Whitelist of top-level keys we will ever emit to values.yaml.
# Adding to this list requires a security review (TM-M18-E-02).
ALLOWED_HELM_SECTIONS: frozenset[str] = frozenset({
    "bundle",
    "replicaCount",
    "resources",
    "podDisruptionBudget",
    "autoscaling",
    "image",
})


@dataclass(frozen=True)
class HelmValuesInput:
    bundle_slug: str
    bundle_version: str
    bundle_manifest_sha256: str
    replica_count: int = 3
    cpu_request: str = "500m"
    cpu_limit: str = "2000m"
    memory_request: str = "1Gi"
    memory_limit: str = "4Gi"
    pdb_enabled: bool = True
    pdb_min_available: int = 2
    autoscaling_enabled: bool = False
    autoscaling_min: int = 1
    autoscaling_max: int = 10
    include_resources: bool = True
    include_pdb: bool = True
    chart_version: str | None = None     # honors EFE_HELM_CHART_VERSION


def render(input_: HelmValuesInput) -> str:
    """Return a deterministic, human-relisable Helm values.yaml.

    Output starts with a comment header documenting the source bundle.
    The body is sorted by key (deterministic for diff-friendliness).

    Audit fix M18-FINAL-A6 (LOW) : `EFE_HELM_CHART_VERSION` env-var
    is sanitised against `_CHART_VERSION_RE`. Values that don't match
    are silently dropped from the output to prevent YAML injection
    via newline-containing env values.
    """
    chart_version = _sanitise_chart_version(
        input_.chart_version
        or os.environ.get("EFE_HELM_CHART_VERSION")
    )

    body: dict[str, Any] = {
        "bundle": {
            "slug": input_.bundle_slug,
            "version": input_.bundle_version,
            "manifest_sha256": input_.bundle_manifest_sha256,
        },
        "replicaCount": int(input_.replica_count),
    }
    if input_.include_resources:
        body["resources"] = {
            "requests": {
                "cpu": str(input_.cpu_request),
                "memory": str(input_.memory_request),
            },
            "limits": {
                "cpu": str(input_.cpu_limit),
                "memory": str(input_.memory_limit),
            },
        }
    if input_.include_pdb:
        body["podDisruptionBudget"] = {
            "enabled": bool(input_.pdb_enabled),
            "minAvailable": int(input_.pdb_min_available),
        }
    if input_.autoscaling_enabled:
        body["autoscaling"] = {
            "enabled": True,
            "min": int(input_.autoscaling_min),
            "max": int(input_.autoscaling_max),
        }

    # TM-M18-E-02 enforcement : drop any key not in the allowlist. This
    # is a defense-in-depth measure ; the dataclass already constrains
    # the keys, but if a future contributor adds a property they MUST
    # also extend ALLOWED_HELM_SECTIONS (CI lint enforces this).
    body = {k: v for k, v in body.items() if k in ALLOWED_HELM_SECTIONS}

    chart_line = (
        f"# chart_version : {chart_version}\n" if chart_version else ""
    )
    header = (
        "# Generated by efe-mcp-server / efe_generate_helm_values\n"
        f"# bundle: {input_.bundle_slug}:{input_.bundle_version}\n"
        f"# manifest_sha256: {input_.bundle_manifest_sha256}\n"
        f"{chart_line}"
        "# IMPORTANT : this file is for review and `helm upgrade -f`. "
        "The MCP server NEVER applies it.\n"
    )
    return header + yaml.safe_dump(
        body, default_flow_style=False, sort_keys=True,
    )
