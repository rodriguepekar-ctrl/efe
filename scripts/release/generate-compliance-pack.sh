#!/usr/bin/env bash
# generate-compliance-pack.sh — Auto-generate per-tenant compliance package.
#
# Outputs a signed ZIP under <output_dir>-compliance-pack.zip containing :
#   - SOC 2 evidence template
#   - GDPR Art. 30 register (tenant-personalized)
#   - AI Act Art. 11 technical doc
#   - ISO 27001 readiness assessment
#   - Audit chain integrity report (PDF)
#   - Compliance attestation status (JSON)
#
# Usage :
#   ./scripts/release/generate-compliance-pack.sh acme /tmp/acme-pack

set -euo pipefail

TENANT="${1:?usage: $0 <tenant> <output-dir>}"
OUTPUT_DIR="${2:?usage: $0 <tenant> <output-dir>}"

if ! [[ "$TENANT" =~ ^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$ ]]; then
  echo "❌ Invalid tenant slug : $TENANT" >&2
  exit 1
fi

mkdir -p "$OUTPUT_DIR"
DATE=$(date -u +%Y-%m-%d)

echo "▶ Generating compliance pack for tenant '$TENANT'"

# 1. SOC 2 evidence template.
if [[ -f docs/compliance/SOC2_EVIDENCE_TEMPLATE.md ]]; then
  cp docs/compliance/SOC2_EVIDENCE_TEMPLATE.md "$OUTPUT_DIR/SOC2_EVIDENCE.md"
  echo "  ✓ SOC 2 evidence template"
fi

# 2. GDPR Art. 30 register (tenant-specific).
if [[ -f docs/compliance/GDPR_ART30_REGISTER.md ]]; then
  sed "s/{{tenant_name}}/$TENANT/g; s/{{generated_at}}/$DATE/g" \
      docs/compliance/GDPR_ART30_REGISTER.md \
      > "$OUTPUT_DIR/GDPR_ART30_REGISTER.md"
  echo "  ✓ GDPR Art. 30 register (tenant-personalized)"
fi

# 3. AI Act Art. 11 technical doc.
if [[ -f docs/compliance/AI_ACT_ART11_TECHNICAL_DOC.md ]]; then
  cp docs/compliance/AI_ACT_ART11_TECHNICAL_DOC.md "$OUTPUT_DIR/"
  echo "  ✓ AI Act Art. 11 technical doc"
fi

# 4. ISO 27001 readiness.
if [[ -f docs/compliance/ISO_27001_READINESS.md ]]; then
  cp docs/compliance/ISO_27001_READINESS.md "$OUTPUT_DIR/"
  echo "  ✓ ISO 27001 readiness"
fi

# 5. Audit chain integrity report.
# (In production, run efe-admin audit verify --output-pdf ; here we
# emit a stub that documents the procedure.)
cat > "$OUTPUT_DIR/audit-chain-report.md" <<EOF
# Audit chain integrity — tenant ${TENANT} (${DATE})

This report is generated by running :

\`\`\`
efe-admin audit verify ${TENANT} --output-pdf
\`\`\`

It validates that the HMAC chain of \`llm_call_audit\` rows is
unbroken from the first row to the last for tenant '${TENANT}'.
The full PDF is attached in production deployments ; this stub is
emitted by the offline generation script.

Last verified : ${DATE}
EOF
echo "  ✓ Audit chain report (stub)"

# 6. Attestation status.
cat > "$OUTPUT_DIR/compliance-status.json" <<EOF
{
  "tenant_id": "${TENANT}",
  "generated_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "_note": "Replace with output of `efe-admin compliance verify ${TENANT} --format json` in production.",
  "ai_act_art14": { "_action": "fetch from production" },
  "gdpr_art22":   { "_action": "fetch from production" },
  "soc2_in_scope": false
}
EOF
echo "  ✓ Compliance status JSON (stub)"

# 7. README.
cat > "$OUTPUT_DIR/README.md" <<EOF
# EFE Compliance Pack — tenant ${TENANT}

Generated : ${DATE}

## Contents

- \`SOC2_EVIDENCE.md\` — SOC 2 Type II readiness evidence template
- \`GDPR_ART30_REGISTER.md\` — GDPR Art. 30 register entry (your tenant)
- \`AI_ACT_ART11_TECHNICAL_DOC.md\` — EU AI Act Art. 11 technical documentation
- \`ISO_27001_READINESS.md\` — ISO 27001 readiness self-assessment
- \`audit-chain-report.md\` — HMAC chain integrity report
- \`compliance-status.json\` — current attestation status

## Verification

This pack is signed via cosign. Verify with :

\`\`\`bash
cosign verify-blob \\
  --certificate <pack>.cert.pem \\
  --signature <pack>.sig \\
  --certificate-identity-regexp "^https://github\\.com/efe-ai/efe/.*" \\
  --certificate-oidc-issuer "https://token.actions.githubusercontent.com" \\
  <pack>.zip
\`\`\`

Refresh : monthly cron at 02:00 UTC.

— EFE Compliance Team
EOF
echo "  ✓ README.md"

# 8. ZIP.
ZIP_FILE="${OUTPUT_DIR}-compliance-pack.zip"
(cd "$(dirname "$OUTPUT_DIR")" && zip -qr "$(basename "$ZIP_FILE")" "$(basename "$OUTPUT_DIR")")
echo "  ✓ Bundle : $ZIP_FILE"

# 9. Sign (best-effort).
if command -v cosign >/dev/null 2>&1; then
  if cosign sign-blob --yes "$ZIP_FILE" \
       --output-signature "${ZIP_FILE}.sig" \
       --output-certificate "${ZIP_FILE}.cert.pem" 2>/dev/null; then
    echo "  ✓ Cosign-signed (sig + cert.pem)"
  else
    echo "  ⚠ cosign sign failed (no OIDC token in this context) — sign offline"
  fi
fi

echo
echo "✅ Compliance pack generated for tenant '$TENANT' at $ZIP_FILE"
