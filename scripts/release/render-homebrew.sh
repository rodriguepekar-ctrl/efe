#!/usr/bin/env bash
# render-homebrew.sh — Render the Homebrew formula with current SHAs.
#
# Inputs (env vars) :
#   VERSION                : 1.0.0
#   VERSION_TAG            : v1.0.0
#   SHA256_DARWIN_X86      : sha256 of the .tar.gz for x86_64-apple-darwin
#   SHA256_DARWIN_ARM      : sha256 of the .tar.gz for aarch64-apple-darwin
#   SHA256_LINUX_X86       : sha256 for x86_64-unknown-linux-musl
#   SHA256_LINUX_ARM       : sha256 for aarch64-unknown-linux-musl
#
# Outputs the rendered Ruby formula on stdout.

set -euo pipefail

: "${VERSION:?VERSION required}"
: "${VERSION_TAG:?VERSION_TAG required}"
: "${SHA256_DARWIN_X86:?SHA256_DARWIN_X86 required}"
: "${SHA256_DARWIN_ARM:?SHA256_DARWIN_ARM required}"
: "${SHA256_LINUX_X86:?SHA256_LINUX_X86 required}"
: "${SHA256_LINUX_ARM:?SHA256_LINUX_ARM required}"

cat <<EOF
# Auto-generated by render-homebrew.sh — do not edit by hand.
# Source : github.com/efe-ai/efe @ ${VERSION_TAG}

class EfeAdmin < Formula
  desc "EFE tenant administration CLI"
  homepage "https://efe.example.com"
  version "${VERSION}"
  license "Apache-2.0"

  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/efe-ai/efe/releases/download/${VERSION_TAG}/efe-admin-${VERSION_TAG}-aarch64-apple-darwin.tar.gz"
      sha256 "${SHA256_DARWIN_ARM}"
    else
      url "https://github.com/efe-ai/efe/releases/download/${VERSION_TAG}/efe-admin-${VERSION_TAG}-x86_64-apple-darwin.tar.gz"
      sha256 "${SHA256_DARWIN_X86}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "https://github.com/efe-ai/efe/releases/download/${VERSION_TAG}/efe-admin-${VERSION_TAG}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${SHA256_LINUX_ARM}"
    else
      url "https://github.com/efe-ai/efe/releases/download/${VERSION_TAG}/efe-admin-${VERSION_TAG}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${SHA256_LINUX_X86}"
    end
  end

  def install
    bin.install "efe-admin"
  end

  test do
    assert_match "efe-admin", shell_output("#{bin}/efe-admin --version")
  end
end
EOF
